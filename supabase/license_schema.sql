-- ═══ Optional: Swagatik Cloud sync (js/modules/sync-supabase.js) ═══════════
-- Each signed-in business (Supabase Auth user) sees ONLY its own snapshots.
create table if not exists public.sync_snapshots (
  id          bigserial primary key,
  owner       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  rev         text not null,
  payload     jsonb not null,
  updated_at  timestamptz not null default now()
);
create index if not exists sync_snapshots_owner_idx on public.sync_snapshots(owner, updated_at desc);
alter table public.sync_snapshots enable row level security;
drop policy if exists "own snapshots" on public.sync_snapshots;
create policy "own snapshots" on public.sync_snapshots for all to authenticated
  using (owner = auth.uid()) with check (owner = auth.uid());
