-- Swagatik — Commercial License API (Supabase / Postgres)            v7.0.0
-- ---------------------------------------------------------------------------
-- What it does
--   • licenses        — one row per sold key: plan, expiry (NULL = lifetime), device limit
--   • license_devices — devices that activated a key (device limit is enforced here)
--   • license_events  — audit trail (activate / check / refused)
--   • activate_license(...) / check_license(...)  — the ONLY things the app can call
--   • sync_snapshots  — optional "Swagatik Cloud" backup per signed-in business (future)
--
-- Security model
--   • Row Level Security is ON for every table and there are NO policies for the
--     anon role → the public anon key cannot read or list keys/devices.
--   • The two RPC functions are SECURITY DEFINER and return only what one device
--     needs to know about one key it already has.
--   • Only the seller (service_role key, or the Supabase dashboard) creates keys.
--
-- How to use: Supabase Dashboard → SQL Editor → paste this file → Run.
-- Then put the project URL + anon key in js/core/license-cloud.js (LICENSE_CLOUD)
-- and set enabled: true. Full steps: COMMERCIAL_LAUNCH.md
-- ═══════════════════════════════════════════════════════════════════════════

create extension if not exists pgcrypto;

-- ── Plans ──────────────────────────────────────────────────────────────────
do $$ begin
  create type license_plan as enum ('TRIAL', 'BASIC', 'PRO', 'BUSINESS', 'LIFETIME');
exception when duplicate_object then null; end $$;

-- ── Keys ───────────────────────────────────────────────────────────────────
create table if not exists public.licenses (
  id            uuid primary key default gen_random_uuid(),
  license_key   text not null unique,                    -- e.g. SWG-7K2Q-9XMA-P4TD (store UPPERCASE)
  company       text not null,                           -- business name the key was sold to
  company_match boolean not null default false,          -- true = company name typed in the app must match
  plan          license_plan not null default 'BASIC',
  expires_at    timestamptz,                             -- NULL = lifetime
  device_limit  int not null default 2 check (device_limit between 1 and 100),
  status        text not null default 'active' check (status in ('active', 'revoked')),
  customer_phone text,
  customer_email text,
  notes         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table if not exists public.license_devices (
  id            uuid primary key default gen_random_uuid(),
  license_id    uuid not null references public.licenses(id) on delete cascade,
  device_id     text not null,                           -- random id generated by the app (pk3_device_id)
  device_name   text,
  app_version   text,
  first_seen    timestamptz not null default now(),
  last_seen     timestamptz not null default now(),
  active        boolean not null default true,           -- set false to free a seat
  unique (license_id, device_id)
);

create table if not exists public.license_events (
  id          bigserial primary key,
  license_id  uuid references public.licenses(id) on delete set null,
  device_id   text,
  event       text not null,                             -- activate | check | refused
  reason      text,
  app_version text,
  at          timestamptz not null default now()
);

create index if not exists license_devices_license_idx on public.license_devices(license_id) where active;
create index if not exists license_events_license_idx on public.license_events(license_id, at desc);

alter table public.licenses        enable row level security;
alter table public.license_devices enable row level security;
alter table public.license_events  enable row level security;
-- (no policies for anon/authenticated: tables are invisible through the public API)

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists licenses_touch on public.licenses;
create trigger licenses_touch before update on public.licenses for each row execute function public.touch_updated_at();

-- ── Result shape returned to the app ───────────────────────────────────────
-- ok, reason (not_found | company_mismatch | expired | revoked | device_limit),
-- plan, company, expires_at, device_limit, devices_used
create or replace function public._license_result(l public.licenses, p_ok boolean, p_reason text)
returns table (ok boolean, reason text, plan text, company text, expires_at timestamptz, device_limit int, devices_used int)
language sql stable as $$
  select p_ok, p_reason, l.plan::text, l.company, l.expires_at, l.device_limit,
         (select count(*)::int from public.license_devices d where d.license_id = l.id and d.active);
$$;

-- ── activate_license: first use of a key on a device ───────────────────────
create or replace function public.activate_license(
  p_key text, p_company text, p_device_id text, p_device_name text default null, p_app_version text default null)
returns table (ok boolean, reason text, plan text, company text, expires_at timestamptz, device_limit int, devices_used int)
language plpgsql security definer set search_path = public as $$
declare
  l public.licenses;
  used int;
begin
  select * into l from public.licenses where license_key = upper(trim(p_key));
  if not found then
    insert into public.license_events(device_id, event, reason, app_version) values (p_device_id, 'refused', 'not_found', p_app_version);
    return query select false, 'not_found'::text, null::text, null::text, null::timestamptz, null::int, null::int; return;
  end if;
  if l.status = 'revoked' then
    insert into public.license_events values (default, l.id, p_device_id, 'refused', 'revoked', p_app_version);
    return query select * from public._license_result(l, false, 'revoked'); return;
  end if;
  if l.expires_at is not null and l.expires_at < now() then
    insert into public.license_events values (default, l.id, p_device_id, 'refused', 'expired', p_app_version);
    return query select * from public._license_result(l, false, 'expired'); return;
  end if;
  if l.company_match and lower(trim(l.company)) <> lower(trim(coalesce(p_company, ''))) then
    insert into public.license_events values (default, l.id, p_device_id, 'refused', 'company_mismatch', p_app_version);
    return query select * from public._license_result(l, false, 'company_mismatch'); return;
  end if;

  -- already registered device → just refresh
  if exists (select 1 from public.license_devices d where d.license_id = l.id and d.device_id = p_device_id and d.active) then
    update public.license_devices set last_seen = now(), app_version = p_app_version, device_name = coalesce(p_device_name, device_name)
      where license_id = l.id and device_id = p_device_id;
  else
    select count(*) into used from public.license_devices d where d.license_id = l.id and d.active;
    if used >= l.device_limit then
      insert into public.license_events values (default, l.id, p_device_id, 'refused', 'device_limit', p_app_version);
      return query select * from public._license_result(l, false, 'device_limit'); return;
    end if;
    insert into public.license_devices(license_id, device_id, device_name, app_version)
      values (l.id, p_device_id, p_device_name, p_app_version)
      on conflict (license_id, device_id) do update set active = true, last_seen = now(), app_version = excluded.app_version;
  end if;

  insert into public.license_events values (default, l.id, p_device_id, 'activate', null, p_app_version);
  return query select * from public._license_result(l, true, null);
end $$;

-- ── check_license: daily re-check from an activated device ─────────────────
create or replace function public.check_license(p_key text, p_device_id text, p_app_version text default null)
returns table (ok boolean, reason text, plan text, company text, expires_at timestamptz, device_limit int, devices_used int)
language plpgsql security definer set search_path = public as $$
declare l public.licenses;
begin
  select * into l from public.licenses where license_key = upper(trim(p_key));
  if not found then
    return query select false, 'not_found'::text, null::text, null::text, null::timestamptz, null::int, null::int; return;
  end if;
  if l.status = 'revoked' then return query select * from public._license_result(l, false, 'revoked'); return; end if;
  if l.expires_at is not null and l.expires_at < now() then return query select * from public._license_result(l, false, 'expired'); return; end if;
  if not exists (select 1 from public.license_devices d where d.license_id = l.id and d.device_id = p_device_id and d.active) then
    return query select * from public._license_result(l, false, 'device_limit'); return;   -- seat was removed by the seller
  end if;
  update public.license_devices set last_seen = now(), app_version = p_app_version where license_id = l.id and device_id = p_device_id;
  insert into public.license_events values (default, l.id, p_device_id, 'check', null, p_app_version);
  return query select * from public._license_result(l, true, null);
end $$;

revoke all on function public.activate_license(text, text, text, text, text) from public;
revoke all on function public.check_license(text, text, text) from public;
grant execute on function public.activate_license(text, text, text, text, text) to anon, authenticated;
grant execute on function public.check_license(text, text, text) to anon, authenticated;

-- ── Seller helper (run in SQL editor / with service_role only) ─────────────
-- select public.new_license('Ram Traders', 'PRO', interval '1 year', 2);      → returns the new key
-- select public.new_license('Sita Furniture', 'LIFETIME', null, 3);
create or replace function public.new_license(p_company text, p_plan license_plan default 'BASIC',
                                              p_valid interval default interval '1 year', p_devices int default 2)
returns text language plpgsql security definer set search_path = public as $$
declare k text;
begin
  loop
    k := 'SWG-' || upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 4)) || '-' || upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 4))
         || '-' || upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 4));
    exit when not exists (select 1 from public.licenses where license_key = k);
  end loop;
  insert into public.licenses(license_key, company, plan, expires_at, device_limit)
    values (k, p_company, p_plan, case when p_valid is null then null else now() + p_valid end, p_devices);
  return k;
end $$;
revoke all on function public.new_license(text, license_plan, interval, int) from public, anon, authenticated;

