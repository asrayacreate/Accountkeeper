function adToBs(ay,am,ad) {
  // Anchor: BS 2083/01/01 = AD 2026/04/14 (verified reference point)
  var ANCHOR_AD = new Date(2026, 3, 14); // April 14, 2026
  var ANCHOR_BS_Y = 2083, ANCHOR_BS_M = 1, ANCHOR_BS_D = 1;
  var target = new Date(ay, am-1, ad);
  var diffDays = Math.round((target - ANCHOR_AD) / 86400000);

  // Walk forward or backward from anchor using BS_MONTHS_DATA
  var by = ANCHOR_BS_Y, bm = ANCHOR_BS_M, bd = ANCHOR_BS_D;

  if (diffDays === 0) return {y:by, m:bm, d:bd};

  if (diffDays > 0) {
    // Forward from anchor
    var rem = diffDays;
    while (rem > 0) {
      var row = BS_MONTHS_DATA[by - 2000];
      if (!row) return {y:by, m:12, d:30};
      var daysInMonth = row[bm] || 30;
      var daysLeft = daysInMonth - bd; // days remaining in current month
      if (rem <= daysLeft) { bd += rem; rem = 0; }
      else {
        rem -= (daysLeft + 1); bd = 1; bm++;
        if (bm > 12) { bm = 1; by++; }
      }
    }
  } else {
    // Backward from anchor
    var rem = -diffDays;
    bd--; // step back one day first
    if (bd < 1) { bm--; if(bm<1){bm=12;by--;} var row=BS_MONTHS_DATA[by-2000]; bd=(row&&row[bm])||30; }
    rem--;
    while (rem > 0) {
      var row = BS_MONTHS_DATA[by - 2000];
      if (!row) return {y:by, m:1, d:1};
      if (rem < bd) { bd -= rem; rem = 0; }
      else {
        rem -= bd; bm--; if(bm<1){bm=12;by--;} row=BS_MONTHS_DATA[by-2000]; bd=(row&&row[bm])||30;
      }
    }
  }
  return {y:by, m:bm, d:bd};
}
