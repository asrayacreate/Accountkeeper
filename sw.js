// Install: pre-cache every file one by one (one missing file must not stop the rest)
self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE_VERSION).then(function (cache) {
      return Promise.all(CORE_ASSETS.map(function (u) {
        return fetch(u, { cache: 'no-cache' }).then(function (r) {
          if (r && r.ok) return cache.put(u, r);
        }).catch(function () {});
      }));
    })
  );
  self.skipWaiting();
});

// Activate: delete old caches
self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (k) {
        if (k !== CACHE_VERSION) return caches.delete(k);
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

// Cache key without "?v=…" so one copy per file is kept.
function cacheKey(req) {
  var u = new URL(req.url);
  u.search = '';
  return u.href;
}

function isCode(req) {
  if (req.mode === 'navigate') return true;
  var u = new URL(req.url);
  return /\/(index\.html)?$/.test(u.pathname) || /\.(js|css|json|html)$/.test(u.pathname);
}

function putInCache(key, resp) {
  try {
    if (resp && resp.status === 200 && resp.type === 'basic') {
      var copy = resp.clone();
      caches.open(CACHE_VERSION).then(function (cache) { cache.put(key, copy); });
    }
  } catch (e) {}
  return resp;
}

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;
  if (new URL(req.url).origin !== self.location.origin) return; // APIs (Dropbox, Drive, AI) go straight to network
  var key = cacheKey(req);

  if (isCode(req)) {
    // Network-first for the app's own code (with 'no-cache' so the HTTP cache revalidates)
    event.respondWith(
      fetch(req, { cache: 'no-cache' }).then(function (resp) { return putInCache(key, resp); })
        .catch(function () {
          return caches.match(key).then(function (c) {
            if (c) return c;
            if (req.mode === 'navigate') return caches.match(new URL('./index.html', self.registration.scope).href);
            return caches.match(req, { ignoreSearch: true });
          });
        })
    );
    return;
  }

  // Cache-first for images and other static files
  event.respondWith(
    caches.match(key).then(function (cached) {
      if (cached) return cached;
      return fetch(req).then(function (resp) { return putInCache(key, resp); });
    })
  );
});
